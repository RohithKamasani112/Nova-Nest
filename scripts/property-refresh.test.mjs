import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const source = fs.readFileSync('src/hooks/usePropertyRefresh.ts', 'utf8');
const code = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
let cleanup, interval, calls = 0, resolve;
const win = new EventTarget();
win.setInterval = cb => { interval = cb; return 1; };
win.clearInterval = () => { interval = null; };
const doc = new EventTarget(); doc.visibilityState = 'visible';
const exports = {};
vm.runInNewContext(code, {exports, window:win, document:doc, require: () => ({useRef:value => ({current:value}), useEffect:fn => { cleanup = fn(); }})});
exports.usePropertyRefresh(async () => { calls++; await new Promise(r => {resolve=r;}); });
const tick = () => new Promise(r => setImmediate(r));
interval(); assert.equal(calls,1);
win.dispatchEvent(new Event('focus')); assert.equal(calls,1, 'overlapping refresh is suppressed');
resolve(); await tick();
doc.visibilityState='hidden'; interval(); assert.equal(calls,1, 'hidden tabs do not poll');
doc.visibilityState='visible'; doc.dispatchEvent(new Event('visibilitychange')); assert.equal(calls,2);
resolve(); await tick();
win.dispatchEvent(new Event('nova-properties-changed')); assert.equal(calls,3);
resolve(); await tick();
const storage = new Event('storage'); storage.key='nova-properties-changed'; win.dispatchEvent(storage); assert.equal(calls,4);
resolve(); await tick();
cleanup(); assert.equal(interval,null); win.dispatchEvent(new Event('focus')); assert.equal(calls,4, 'listeners are removed');
console.log('Refresh lifecycle checks passed: focus, visibility, same-tab changes, cross-tab changes, serialization and cleanup.');
